#pragma once

#include <vxe/core/types.hpp>

#include <string>
#include <variant>

// Events from the operating system, translated from SDL into engine types so
// nothing above the platform module ever sees SDL (ADR-004).
//
// Keys are identified by scancode: the physical key position as a USB HID
// usage id (the same numbers SDL_Scancode uses, for example 4 is the key
// labeled A on a US keyboard). Physical positions keep WASD on the same keys
// for every keyboard layout (Section 17.2). The input system turns them into
// actions; Platform::keyName() gives the label for the keybind screen.
namespace vxe::platform {

// Modifier keys held during a key or mouse event.
enum class Modifiers : u8 {
    None = 0,
    Shift = 1U << 0U,
    Ctrl = 1U << 1U,
    Alt = 1U << 2U,
    Gui = 1U << 3U, // The Windows or Command key.
};

[[nodiscard]] constexpr Modifiers operator|(Modifiers a, Modifiers b) noexcept {
    return static_cast<Modifiers>(static_cast<u8>(a) | static_cast<u8>(b));
}
[[nodiscard]] constexpr bool hasAll(Modifiers held, Modifiers wanted) noexcept {
    return (static_cast<u8>(held) & static_cast<u8>(wanted)) == static_cast<u8>(wanted);
}

// Mouse buttons, numbered like SDL (1 left, 2 middle, 3 right, 4 and 5 side).
enum class MouseButton : u8 {
    Left = 1,
    Middle = 2,
    Right = 3,
    X1 = 4,
    X2 = 5,
};

// The user asked to quit (closing the last window, Alt+F4, the OS shutting down).
struct QuitRequested {};

// Window size in logical units (what UI layout uses).
struct WindowResized {
    i32 width = 0;
    i32 height = 0;
};

// Framebuffer size in pixels (what rendering uses). Differs from the logical
// size on high DPI screens.
struct WindowPixelSizeChanged {
    i32 width = 0;
    i32 height = 0;
};

struct WindowFocusChanged {
    bool focused = false;
};

struct WindowMinimizedChanged {
    bool minimized = false;
};

// The content scale changed, for example after dragging the window to a
// monitor with a different DPI setting. UI scale "Auto" follows this.
struct DisplayScaleChanged {
    f32 scale = 1.0F;
};

struct KeyEvent {
    u16 scancode = 0;
    bool down = false;
    bool repeat = false; // Generated by holding the key, not a new press.
    Modifiers modifiers = Modifiers::None;
};

struct MouseButtonEvent {
    MouseButton button = MouseButton::Left;
    bool down = false;
    u8 clicks = 1; // 2 for a double click.
    f32 x = 0.0F;  // Position in logical window units.
    f32 y = 0.0F;
};

struct MouseMotionEvent {
    f32 x = 0.0F; // Position in logical window units.
    f32 y = 0.0F;
    f32 dx = 0.0F; // Relative motion. In relative mouse mode this is raw,
    f32 dy = 0.0F; // unaccelerated device motion (Section 17.1).
};

struct MouseWheelEvent {
    f32 x = 0.0F; // Positive to the right.
    f32 y = 0.0F; // Positive away from the user.
};

// Text typed by the user (UTF-8), already composed by the OS input method.
// Separate from key events because one key can produce no text or several
// characters, depending on the layout.
struct TextInputEvent {
    std::string text;
};

using PlatformEvent = std::variant<QuitRequested, WindowResized, WindowPixelSizeChanged, WindowFocusChanged,
                                   WindowMinimizedChanged, DisplayScaleChanged, KeyEvent, MouseButtonEvent,
                                   MouseMotionEvent, MouseWheelEvent, TextInputEvent>;

} // namespace vxe::platform
